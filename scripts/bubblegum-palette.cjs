// Run after adding presentation colors. Converts literals to paired CSS tokens;
// never uses a filter on the page or changes image/rarity artwork.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const postcss = require('postcss');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'src/app/bubblegum-palette.css');
const walk = dir => fs.readdirSync(dir, {withFileTypes:true}).flatMap(e => e.isDirectory() ? walk(path.join(dir,e.name)) : [path.join(dir,e.name)]);
const files = walk(path.join(root,'src')).filter(f => f.endsWith('.css') && f !== output && !/AnimeBorderArtwork|EquippedToyEffect|TributeFurnace|TributeGoalBar|item-rarity/.test(f));
const tokens = new Map();
if (fs.existsSync(output)) {
  const old = postcss.parse(fs.readFileSync(output,'utf8'));
  old.walkRules(rule => rule.walkDecls(d => {
    if (!d.prop.startsWith('--bb-c-')) return;
    const pair = tokens.get(d.prop) || {};
    pair[rule.selector.includes('data-color-mode') ? 'dark' : 'light'] = d.value;
    tokens.set(d.prop,pair);
  }));
}
function hsl(raw) {
  if (/^hsl/i.test(raw)) { const n=raw.match(/[\d.]+/g).map(Number); return [n[0],n[1],n[2],n[3]??1]; }
  let rgb,a=1;
  if (raw.startsWith('#')) { let h=raw.slice(1);if(h.length<=4)h=[...h].map(c=>c+c).join('');rgb=[0,2,4].map(i=>parseInt(h.slice(i,i+2),16)/255);if(h.length===8)a=parseInt(h.slice(6,8),16)/255; }
  else {const n=raw.match(/[\d.]+/g).map(Number);rgb=n.slice(0,3).map(v=>v/255);a=n[3]??1;}
  const [r,g,b]=rgb,max=Math.max(...rgb),min=Math.min(...rgb),d=max-min,l=(max+min)/2;
  const h=d===0?275:max===r?(((g-b)/d)%6)*60:max===g?((b-r)/d+2)*60:((r-g)/d+4)*60;
  return [(h+360)%360,d===0?0:d/(1-Math.abs(2*l-1))*100,l*100,a];
}
function dark(raw,kind) {
  let [h,s,l,a]=hsl(raw);
  if(kind==='shadow')return `rgb(0 0 0 / ${Math.min(.45,a+.08).toFixed(3)})`;
  if(kind==='bg'){if(h<90||h>325)h=310;else if(h>=90&&h<220)h=255;s=Math.min(32,Math.max(18,s));l=Math.min(26,11+(100-l)*.20);}
  else if(kind==='line'){s=Math.min(36,Math.max(18,s));l=44;}
  else{s=Math.min(74,Math.max(18,s));l=94-l*.22;}
  return `hsl(${Math.round(h)} ${Math.round(s)}% ${Math.round(l)}% / ${a.toFixed(3)})`;
}
const rx=/#(?:[\da-f]{8}|[\da-f]{6}|[\da-f]{4}|[\da-f]{3})\b|(?:rgba?|hsla?)\([\d.,%\s/]+\)/gi;
for(const file of files){
  const tree=postcss.parse(fs.readFileSync(file,'utf8'));
  tree.walkDecls(d=>{
    if(/mask/.test(d.prop)||d.value.includes('var(--bb-c-')||! /color|background|border|outline|shadow|^--|fill|stroke|filter/.test(d.prop))return;
    const kind=/shadow|filter/.test(d.prop)?'shadow':/border|outline|line/.test(d.prop)?'line':/background|surface|stage-bg|glow|paper|lilac|cyan|lemon|pink/.test(d.prop)?'bg':'ink';
    d.value=d.value.replace(rx,raw=>{
      const key='--bb-c-'+crypto.createHash('sha1').update(kind+':'+raw.toLowerCase()).digest('hex').slice(0,10);
      tokens.set(key,{light:raw,dark:dark(raw,kind)});
      return `var(${key}, ${raw})`;
    });
  });
  fs.writeFileSync(file,tree.toString());
}
for (const [key,pair] of tokens) { const kind=['bg','ink','line','shadow'].find(k=>'--bb-c-'+crypto.createHash('sha1').update(k+':'+pair.light.toLowerCase()).digest('hex').slice(0,10)===key); if(kind)pair.dark=dark(pair.light,kind); }
let css='/* Generated by scripts/bubblegum-palette.cjs. Light is the approved Bubblegum palette. */\n';
for(const [selector,mode]of [[':root','light'],[':root[data-color-mode="dark"]','dark']]){
  css+=selector+' {\n'+[...tokens].sort(([a],[b])=>a.localeCompare(b)).map(([key,pair])=>`  ${key}: ${pair[mode]};`).join('\n')+'\n}\n';
}
fs.writeFileSync(output,css);
console.log(`Paired ${tokens.size} presentation colors across ${files.length} stylesheets.`);
