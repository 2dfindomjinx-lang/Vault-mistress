async function debt(amounts=[19,19,19,18],status="active") {
  const user=randomUUID(), id=randomUUID(), code="TD-"+id.replaceAll("-","").slice(0,8).toUpperCase();
  await db.query("insert into auth.users values ($1)",[user]);
  await db.query("insert into profiles(id) values ($1)",[user]);
  await db.query(`insert into throne_debts(id,user_id,debt_code,status,total_amount_usd,installment_amount_usd,installment_count,repayment_frequency,contract_length_weeks)
    values($1,$2,$3,$4,$5,$6,$7,'weekly',4)`,[id,user,code,status,amounts.reduce((a,b)=>a+b,0),amounts[0],amounts.length]);
  for(let n=0;n<amounts.length;n++) await db.query("insert into throne_debt_installments(debt_id,installment_number,amount_usd,due_date) values($1,$2,$3,now()+interval '1 week')",[id,n+1,amounts[n]]);
  return {id,user,code};
}
async function pay(d, cents, options={}) {
  const event=options.id??randomUUID();
  const payload={contract_version:"1",event_type:"gift_purchased",data:{message:options.code??d.code,price:cents,currency:options.currency??"USD"}};
  await db.query("insert into throne_webhook_events(event_id,payload,occurred_at) values($1,$2,$3)",[event,JSON.stringify(payload),options.time??new Date().toISOString()]);
  const result=(await db.query("select apply_throne_debt_payment($1) as result",[event])).rows[0].result;
  return {...result,event};
}
