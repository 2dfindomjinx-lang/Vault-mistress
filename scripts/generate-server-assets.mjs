import fs from "node:fs";
import path from "node:path";
import { buildOverlayManifest } from "./overlay-media-manifest.mjs";

// Only this build-time script enumerates asset folders. Runtime modules receive
// filenames, not filesystem globs that pull unrelated media into every function.
const root = process.cwd();
const output = path.join(root, "src/lib/generated");
fs.mkdirSync(output, { recursive: true });
const images = /\.(avif|gif|jfif|jpe?g|png|webp)$/i;
function walk(folder) {
  return fs.readdirSync(folder, { withFileTypes: true }).flatMap(entry => {
    const file = path.join(folder, entry.name);
    return entry.isDirectory() ? walk(file) : [file];
  });
}
function catalog(folder, sortNames = false) {
  const result = {};
  for (const file of walk(path.join(root, folder)).filter(file => images.test(file))) {
    const relative = path.relative(path.join(root, folder), file);
    const category = path.dirname(relative).replaceAll("\\", "/");
    (result[category] ??= []).push(path.basename(file));
  }
  if (sortNames) for (const names of Object.values(result)) names.sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }));
  return result;
}
fs.writeFileSync(path.join(output, "asset-names.json"), JSON.stringify({
  worship: catalog("private/worship", true), shrine: catalog("public/shrine"),
}, null, 2) + "\n");

const overlayRoot = path.join(root, "public/principessa-discipline/overlay-pool");
for (const [name, includeMedia] of [["overlay-manifest.json", false], ["overlay-media-manifest.json", true]]) {
  fs.writeFileSync(path.join(output, name), JSON.stringify(buildOverlayManifest(overlayRoot, includeMedia), null, 2) + "\n");
}

// Explicit literal paths let Next trace only the crate art needed by OG cards.
const crateFiles = walk(path.join(root, "public/crate-items")).filter(file => images.test(file));
const lines = crateFiles.map(file => {
  const relative = path.relative(root, file).replaceAll("\\", "/");
  return `  ${JSON.stringify("/" + relative.slice(7))}: () => readFile(path.join(process.cwd(), ${JSON.stringify(relative)})),`;
});
fs.writeFileSync(path.join(output, "crate-image-readers.ts"), `// Generated by scripts/generate-server-assets.mjs.\nimport { readFile } from "node:fs/promises";\nimport path from "node:path";\nexport const crateImageReaders: Record<string, () => Promise<Buffer>> = {\n${lines.join("\n")}\n};\n`);
console.log(`Generated server asset manifests and ${crateFiles.length} literal crate image readers.`);
