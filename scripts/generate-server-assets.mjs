import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import sharp from "sharp";
import { privateMediaManifest, verifyPrivateMedia } from "./private-media-storage.mjs";
import { buildOverlayManifest } from "./overlay-media-manifest.mjs";

// Only this build-time script enumerates asset folders. Runtime modules receive
// filenames, not filesystem globs that pull unrelated media into every function.
const root = process.cwd();
const output = path.join(root, "src/lib/generated");
fs.mkdirSync(output, { recursive: true });
const images = /\.(avif|gif|jfif|jpe?g|png|webp)$/i;
function walk(folder) {
  return fs.readdirSync(folder, { withFileTypes: true }).flatMap(entry => {
    const file = path.join(folder, entry.name);
    return entry.isDirectory() ? walk(file) : [file];
  });
}
function catalog(folder, sortNames = false) {
  const result = {};
  for (const file of walk(path.join(root, folder)).filter(file => images.test(file))) {
    const relative = path.relative(path.join(root, folder), file);
    const category = path.dirname(relative).replaceAll("\\", "/");
    (result[category] ??= []).push(path.basename(file));
  }
  if (sortNames) for (const names of Object.values(result)) names.sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }));
  return result;
}
fs.writeFileSync(path.join(output, "asset-names.json"), JSON.stringify({
  worship: catalog("private/worship", true), shrine: catalog("public/shrine"),
}, null, 2) + "\n");

const overlayRoot = path.join(root, "public/principessa-discipline/overlay-pool");
for (const [name, includeMedia] of [["overlay-manifest.json", false], ["overlay-media-manifest.json", true]]) {
  fs.writeFileSync(path.join(output, name), JSON.stringify(buildOverlayManifest(overlayRoot, includeMedia), null, 2) + "\n");
}

// Explicit literal paths let Next trace only the crate art needed by OG cards.
const crateFiles = walk(path.join(root, "public/crate-items")).filter(file => images.test(file));
const thumbnailRoot = path.join(root, "private/generated-og");
fs.mkdirSync(thumbnailRoot, { recursive: true });
const lines = [];
for (const file of crateFiles.sort()) {
  const relative = path.relative(root, file).replaceAll("\\", "/");
  const source = fs.readFileSync(file);
  const hash = createHash("sha256").update("og256-png90-v1").update(source).digest("hex").slice(0, 24);
  const target = `private/generated-og/${hash}.png`;
  if (!fs.existsSync(path.join(root, target))) {
    await sharp(source).rotate().resize(256, 256, { fit: "inside", withoutEnlargement: true })
      .png({ palette: true, quality: 90 }).toFile(path.join(root, target));
  }
  lines.push(`  ${JSON.stringify("/" + relative.slice(7))}: () => readFile(path.join(process.cwd(), ${JSON.stringify(target)})),`);
}
fs.writeFileSync(path.join(output, "crate-image-readers.ts"), `// Generated by scripts/generate-server-assets.mjs.\nimport { readFile } from "node:fs/promises";\nimport path from "node:path";\nexport const crateImageReaders: Record<string, () => Promise<Buffer>> = {\n${lines.join("\n")}\n};\n`);
console.log(`Generated server asset manifests and ${crateFiles.length} literal crate image readers.`);

// Generate one backend, not a runtime fallback that traces both backends.
const privateEntries = await privateMediaManifest(root);
const remotePrivateMedia = process.env.PRIVATE_MEDIA_STORAGE === "supabase";
if (remotePrivateMedia) await verifyPrivateMedia(privateEntries);
for (const area of ["gallery", "worship"]) {
const areaEntries = Object.fromEntries(Object.entries(privateEntries).filter(([name]) => name.startsWith(area + "/")));
const privateReader = remotePrivateMedia
  ? `import { createSupabaseAdminClient } from "@/lib/supabase/admin";
const objects: Record<string, string> = ${JSON.stringify(Object.fromEntries(Object.entries(areaEntries).map(([name, entry]) => [name, entry.key])))};
export async function readPrivateMedia(key: string): Promise<Uint8Array> {
  if (!objects[key]) throw new Error("Private media not found");
  const { data, error } = await createSupabaseAdminClient().storage.from("vault-private-media").download(objects[key]);
  if (error || !data) throw new Error("Private media unavailable");
  return new Uint8Array(await data.arrayBuffer());
}`
  : `import { readFile } from "node:fs/promises";
import path from "node:path";
const readers: Record<string, () => Promise<Buffer>> = {
${Object.keys(areaEntries).map(name => '  '+JSON.stringify(name)+': () => readFile(path.join(process.cwd(), '+JSON.stringify('private/'+name)+')),').join('\n')}
};
export async function readPrivateMedia(key: string): Promise<Uint8Array> {
  if (!readers[key]) throw new Error("Private media not found");
  return readers[key]();
}`;
fs.writeFileSync(path.join(output, `${area}-media-reader.ts`), "// Generated by scripts/generate-server-assets.mjs.\n" + privateReader + "\n");
}
console.log("Private media backend: " + (remotePrivateMedia ? "authenticated storage proxy" : "local"));
