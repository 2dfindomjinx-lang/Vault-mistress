import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
const db = new PGlite();
const user = randomUUID(), other = randomUUID();
const rpc = async (sql, args) => (await db.query(sql, args)).rows[0].result;
const shop = (id, action = "buy", item = "royal") => rpc("select execute_money_shop($1,$2,$3,$4,38,27) result", [user,id,action,item]);
const spin = (id, amount = 4, kind = "chastity", wheel = "chastity") => rpc("select spin_findom_wheel_once($1,$2,$3,$4,2,$5,'4 hours',0,null) result", [user,id,wheel,kind,amount]);
const balance = async () => (await db.query("select principessa_money n from profiles where id=$1",[user])).rows[0].n;
const quantity = async () => (await db.query("select quantity n from user_crate_inventory where user_id=$1 and variant='normal'",[user])).rows[0]?.n ?? 0;
try {
  await db.exec(`create role anon; create role authenticated; create role service_role;
    create table profiles(id uuid primary key,principessa_money integer not null,chastity_until timestamptz,updated_at timestamptz);
    create table crate_items(item_id text primary key,rarity text);
    create table user_crate_inventory(user_id uuid,item_id text references crate_items(item_id),variant text,quantity integer check(quantity>0),pm_quantity integer check(pm_quantity>=0 and pm_quantity<=quantity),unique(user_id,item_id,variant));
    create table money_transactions(user_id uuid,amount integer,balance_before integer,balance_after integer,reason text,metadata jsonb);
    create table wheel_spins(id uuid primary key default gen_random_uuid(),user_id uuid,wheel_id text,kind text,segment_label text,amount numeric,pay_code text,amount_owed_usd numeric,status text);
    insert into profiles values('${user}',1000,null,now()),('${other}',1000,null,now());
    insert into crate_items values('royal','legendary'),('common','common');
    insert into user_crate_inventory values('${user}','royal','shiny',3,0);`);
  await db.exec(await readFile('supabase/wheel-chastity-hours.sql','utf8'));
  const migration = await readFile('supabase/202610060001_paid_operation_receipts.sql','utf8');
  await db.exec(migration); await db.exec(migration);
  const id = randomUUID();
  assert.equal((await shop(id)).success,true);
  assert.equal(await balance(),962); assert.equal(await quantity(),1);
  assert.equal((await shop(id)).replayed,true); assert.equal(await balance(),962);
  assert.equal((await shop(id,'sell')).error,'request_mismatch');
  assert.equal((await shop(randomUUID(),'buy','common')).error,'invalid_item');
  await Promise.all([shop(randomUUID()),shop(randomUUID())]);
  assert.equal(await quantity(),3); assert.equal(await balance(),886);
  const sell = randomUUID(); await shop(sell,'sell'); await shop(sell,'sell');
  assert.equal(await quantity(),2); assert.equal(await balance(),913);
  // Force a failure after inventory+wallet mutations; SQL must undo both.
  await db.exec(`create function reject_ledger() returns trigger language plpgsql as $$ begin raise exception 'ledger failed'; end $$;
    create trigger reject_ledger before insert on money_transactions for each row execute function reject_ledger();`);
  await assert.rejects(shop(randomUUID()),/ledger failed/);
  await assert.rejects(shop(randomUUID(),'sell'),/ledger failed/);
  assert.equal(await quantity(),2); assert.equal(await balance(),913);
  await db.exec('drop trigger reject_ledger on money_transactions');
  const wheel = randomUUID(); const first = await spin(wheel);
  const repeat = await spin(wheel,240);
  assert.equal(repeat.spinId,first.spinId); assert.deepEqual(repeat.segment,first.segment);
  assert.equal(repeat.chastityUntil,first.chastityUntil); assert.equal(await balance(),911);
  assert.equal((await spin(wheel,4,'money','broke')).error,'request_mismatch');
  const moneyId = randomUUID(); const money = await spin(moneyId,25,'money','broke');
  assert.equal((await spin(moneyId,500,'money','broke')).payCode,money.payCode);
  assert.equal((await spin(randomUUID(),25,'money','broke')).error,'unpaid_spin');
  await db.exec(`create function reject_receipt() returns trigger language plpgsql as $$ begin raise exception 'receipt failed'; end $$;
    create trigger reject_receipt before insert on paid_operation_receipts for each row execute function reject_receipt();`);
  const before = await balance();
  await assert.rejects(spin(randomUUID()),/receipt failed/);
  await assert.rejects(shop(randomUUID()),/receipt failed/);
  assert.equal(await balance(),before); assert.equal(await quantity(),2);
  await db.exec('drop trigger reject_receipt on paid_operation_receipts');
  await shop(randomUUID(),'sell'); await shop(randomUUID(),'sell');
  assert.equal(await quantity(),0); assert.equal((await shop(randomUUID(),'sell')).error,'no_shop_copy');
  assert.equal((await db.query("select quantity from user_crate_inventory where variant='shiny'")).rows[0].quantity,3);
  await db.exec(`create table court_wheel_debts(user_id uuid,status text); insert into court_wheel_debts values('${user}','unpaid');`);
  assert.equal((await spin(randomUUID())).error,'unpaid_spin');
  assert.equal((await spin(wheel)).spinId,first.spinId,'Old debt never blocks a receipt replay');
  await db.exec('set role authenticated');
  await assert.rejects(shop(randomUUID()),/permission denied for function/);
  await assert.rejects(spin(randomUUID()),/permission denied for function/);
  await assert.rejects(db.query('select * from paid_operation_receipts'),/permission denied/);
  await db.exec('reset role');
  console.log('Paid operations: buy/sell, inventory variants, ledger/receipt rollback, wheel replay, preserved hours, debt ordering and privileges passed. PGlite does not simulate independent PostgreSQL connections.');
} finally { await db.close(); }
